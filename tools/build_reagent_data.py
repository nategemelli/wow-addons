"""Generate AuctionPeek's offline reagent index from the Forever client tables.

Give the script a directory containing the four CSVs and the ZIP named below.
The output is deterministic; the addon never downloads data or opens recipes.
"""

import argparse
import csv
import hashlib
import json
import re
from collections import Counter, defaultdict
from pathlib import Path
from zipfile import ZipFile


BUILD = "1.60.1.70938"
TABLES = {
    "SkillLineAbility": "6696abd03ef90ad250a12ac23778616c292c46f6a0082130fbe187c96ead0aa0",
    "TradeSkillCategory": "96d291070c6e099a16e5251fcf511cdfe0fef700a7dc1d691d8839c8633699c8",
    "SpellReagents": "be6e987755f7097348eb072073ae3175b3d56016f43f90615a081d33d6affff6",
    "SpellName": "bd8dc963dd691c69aff531464636e7b5a944efeedb773895e7b2c4a0fb7c38b4",
}
ZIP_NAME = "ProfessionDB-ProfessionDB-v1.10.0.zip"
ZIP_HASH = "f146d5d82347033ec381f42150bfa4d4379149e41d9efe5c0d4ff291a64c3639"
PROFESSIONS = {
    40: "Rogue Poisons", 129: "First Aid", 164: "Blacksmithing", 165: "Leatherworking",
    171: "Alchemy", 182: "Herbalism", 185: "Cooking", 186: "Mining", 197: "Tailoring",
    202: "Engineering", 333: "Enchanting", 356: "Fishing", 393: "Skinning",
}
# These SoD poisons share the regular Poisons category in Forever's DB2.
# https://foreverdb.net/class/Rogue/poisons lists them separately from Forever's ranks.
SEASONAL_POISONS = {439500, 439503, 439505, 458822, 1214168}


def checked_path(path, checksum):
    if hashlib.sha256(path.read_bytes()).hexdigest() != checksum:
        raise ValueError(f"Unexpected contents of {path.name}")
    return path


def read_table(directory, name):
    """wago.tools/db2/<table>/csv?build=1.60.1.70938 (enUS)."""
    path = checked_path(directory / f"{name}.{BUILD}.csv", TABLES[name])
    with path.open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def generate(directory, output):
    categories = {int(row["ID"]): row["Name_lang"] for row in read_table(directory, "TradeSkillCategory")}
    names = {int(row["ID"]): row["Name_lang"] for row in read_table(directory, "SpellName")}
    materials = {}
    for row in read_table(directory, "SpellReagents"):
        materials[int(row["SpellID"])] = {
            int(row[f"Reagent_{i}"]) for i in range(8)
            if int(row[f"Reagent_{i}"]) > 0 and int(row[f"ReagentCount_{i}"]) > 0
        }
    with ZipFile(checked_path(directory / ZIP_NAME, ZIP_HASH)) as archive:
        hidden_file = archive.read("ProfessionDB/Data/Forever/_core/HiddenRecipes.lua").decode("utf-8")
        hidden = {int(spell) for spell in re.findall(r"\[(\d+)\]=true", hidden_file)}
        license_text = archive.read("ProfessionDB/LICENSE").decode("utf-8").strip()

    uses = defaultdict(lambda: defaultdict(dict))
    accepted = set()
    skipped = Counter()
    for row in read_table(directory, "SkillLineAbility"):
        spell, skill = int(row["Spell"]), int(row["SkillLine"])
        if skill not in PROFESSIONS or not materials.get(spell):
            continue
        category = categories.get(int(row["TradeSkillCategoryID"]))
        if category == "SEASON OF DISCOVERY" or spell in SEASONAL_POISONS:
            skipped["seasonal"] += 1
            continue
        if int(row["AcquireMethod"]) == 3 or spell in hidden:
            skipped["retired or hidden"] += 1
            continue
        # Basic Campfire is a Cooking skill outside the recipe window. Other
        # uncategorized abilities can be internal or leftovers from SoD.
        if not category and spell != 818:
            skipped["uncategorized"] += 1
            continue
        name = names[spell].strip()
        if not name:
            raise ValueError(f"Missing name for spell {spell}")
        accepted.add((skill, spell))
        # Keep the first rank that actually consumes this material. In
        # particular, higher poison ranks change reagents and vial types.
        family = re.sub(r" [IVX]+$", "", name) if skill == 40 else name
        # Within the same 75-point skill band, prefer simpler crafts and the
        # familiar Classic recipe when an equally simple new one is present.
        yellow = int(row["TrivialSkillLineRankLow"]) or 9999
        priority = ((yellow - 1) // 75, len(materials[spell]), spell >= 400000, yellow, spell, name)
        for item in materials[spell]:
            recipes = uses[item][PROFESSIONS[skill]]
            if family not in recipes or priority < recipes[family]:
                recipes[family] = priority

    lines = [
        "-- Generated by tools/build_reagent_data.py for WoW Forever " + BUILD + ".",
        "-- Sources: Blizzard SkillLineAbility, TradeSkillCategory, SpellName and SpellReagents.",
        f"-- CSVs: https://wago.tools/db2/SpellReagents?build={BUILD}",
        "-- Hidden-recipe exclusions: LibProfessionDB v1.10.0 (incorporating AllTheThings).",
        "-- https://www.curseforge.com/wow/addons/libprofessiondb/files/9619259",
        "--[[", license_text, "]]", "", "local _, ns = ...", "", "ns.reagentUses = {",
    ]
    for item, professions in sorted(uses.items()):
        lines.append(f"    [{item}] = {{")
        for profession, recipes in sorted(professions.items()):
            examples = (choice[-1] for choice in sorted(recipes.values())[:2])
            strings = ", ".join(json.dumps(name, ensure_ascii=False) for name in examples)
            lines.append(f'        {{ profession = "{profession}", examples = {{ {strings} }}, total = {len(recipes)} }},')
        lines.append("    },")
    lines.append("}")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(accepted)} recipe spells across {len(PROFESSIONS)} professions and skills, {len(uses)} materials.")
    print("Excluded material-consuming ability rows:", dict(skipped))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source_directory", type=Path)
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "AuctionPeek" / "ReagentData.lua")
    args = parser.parse_args()
    generate(args.source_directory, args.output)
